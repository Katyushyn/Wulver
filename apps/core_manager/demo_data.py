def _get_or_create_page(title):
    slug = title.lower().replace(" ", "-")
    page, created = Page.objects.get_or_create(
        slug=slug,
        defaults={
            "title": title,
            "description": f"Demo content for {title}.",
            "template": None,
            "is_published": True,
        },
    )
    changed_fields = []
    if page.title != title:
        page.title = title
        changed_fields.append("title")
    if not page.is_published:
        page.is_published = True
        changed_fields.append("is_published")
    if changed_fields:
        page.save(update_fields=changed_fields)
    return page


def _get_or_create_category(title, slug, parent=None, sort_order=0):
    category, _created = Category.objects.get_or_create(
        slug=slug,
        defaults={
            "title": title,
            "parent": parent,
            "description": f"Demo category: {title}",
            "intro": f"Demo content for the {title} category.",
            "sort_order": sort_order,
        },
    )
    changed_fields = []
    for field_name, value in {
        "title": title,
        "parent": parent,
        "sort_order": sort_order,
    }.items():
        if getattr(category, field_name) != value:
            setattr(category, field_name, value)
            changed_fields.append(field_name)
    if changed_fields:
        category.save(update_fields=changed_fields)
    return category


def _make_article_image(category_slug, article_number):
    source_path = DEMO_ASSETS_DIR / DEMO_ARTICLES[category_slug]["image"]
    with Image.open(source_path) as source:
        image = source.convert("RGB")

    if article_number % 2 == 0:
        image = ImageOps.mirror(image)

    width, height = image.size
    inset = int(min(width, height) * (article_number - 1) * 0.012)
    if inset:
        image = image.crop((inset, inset // 2, width - inset, height - inset // 2))

    image = ImageOps.fit(
        image,
        (1200, 800),
        method=Image.Resampling.LANCZOS,
        centering=(0.42 + article_number * 0.025, 0.5),
    )
    image = ImageEnhance.Contrast(image).enhance(0.96 + article_number * 0.018)
    image = ImageEnhance.Color(image).enhance(0.94 + article_number * 0.02)

    output = BytesIO()
    image.save(output, format="JPEG", quality=92, optimize=True)
    return ContentFile(output.getvalue())


def _replace_article_image(article, category_slug, article_number):
    image_stem = f"demo-{category_slug}-article-{article_number}"

    for field_name in ("img", "img_crop", "img_crop_mob"):
        field = getattr(article, field_name)
        if field:
            field.delete(save=False)

    media_root = Path(settings.MEDIA_ROOT).resolve()
    for source_file in media_root.glob(f"post/**/{image_stem}*.jpg"):
        if source_file.is_file() and media_root in source_file.resolve().parents:
            source_file.unlink()

    article.img.save(
        f"{image_stem}.jpg",
        _make_article_image(category_slug, article_number),
        save=False,
    )


def _get_or_create_articles(category, author=None):
    created_count = 0
    article_specs = DEMO_ARTICLES[category.slug]["items"]

    for article_number, spec in enumerate(article_specs, start=1):
        slug = f"demo-{category.slug}-article-{article_number}"
        article, created = Article.objects.get_or_create(
            slug=slug,
            defaults={"title": spec["title"]},
        )
        if created:
            created_count += 1

        article.title = spec["title"]
        article.description = spec["description"]
        article.meta_title = spec["title"]
        article.meta_description = spec["description"]
        article.author = author or article.author
        article.category = category
        article.intro = spec["intro"]
        article.body = spec["body"]
        article.is_published = True
        if created:
            article.publish = timezone.now()

        _replace_article_image(article, category.slug, article_number)
        article.save()

    return created_count


@transaction.atomic
def create_demo_data(author=None):
    pages = {title.lower(): _get_or_create_page(title) for title in DEMO_PAGE_TITLES}
    blog = _get_or_create_category("Blog", "blog", sort_order=1)
    news = _get_or_create_category("News", "news", parent=blog, sort_order=1)
    news_parent = _get_or_create_category("News parent", "news-parent", parent=news, sort_order=1)
    news_2 = _get_or_create_category("News 2", "news-2", parent=blog, sort_order=2)
    categories = {"blog": blog, "news": news, "news-parent": news_parent, "news-2": news_2}

    created_articles = sum(
        _get_or_create_articles(categories[slug], author=author)
        for slug in DEMO_ARTICLE_CATEGORIES
    )
    Category.normalize_sort_order()
    site_settings = SiteSettings.get_solo()
    if not site_settings.home_page_id:
        site_settings.home_page = pages["home"]
        site_settings.save(update_fields=["home_page"])

    return {
        "pages": len(pages),
        "categories": len(categories),
        "articles_created": created_articles,
        "articles_total": Article.objects.filter(slug__startswith="demo-", category__slug__in=DEMO_ARTICLE_CATEGORIES).count(),
    }
